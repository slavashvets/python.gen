def _generated_package(generated_tree: Path) -> Path:
    return generated_tree / PACKAGE


def _python_paths(generated_tree: Path) -> list[Path]:
    return sorted(_generated_package(generated_tree).rglob("*.py"))


def _statement_paths(generated_tree: Path) -> dict[str, Path]:
    statements = _generated_package(generated_tree) / "_generated" / "statements"
    return {path.stem: path for path in statements.glob("*.py") if path.name != "__init__.py"}


def _parse(path: Path) -> ast.Module:
    return ast.parse(path.read_text(), filename=str(path))


def _sql_assignments(tree: ast.Module) -> list[ast.expr]:
    assignments: list[ast.expr] = []
    for node in tree.body:
        if isinstance(node, ast.Assign):
            if any(isinstance(target, ast.Name) and target.id == "SQL" for target in node.targets):
                assignments.append(node.value)
        elif (
            isinstance(node, ast.AnnAssign)
            and isinstance(node.target, ast.Name)
            and node.target.id == "SQL"
            and node.value is not None
        ):
            assignments.append(node.value)
    return assignments


def _top_function(tree: ast.Module, name: str) -> ast.FunctionDef | ast.AsyncFunctionDef:
    matches = [
        node for node in tree.body if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == name
    ]
    assert len(matches) == 1, f"expected one top-level function {name}, found {len(matches)}"
    return matches[0]


def _call_leaf(call: ast.Call) -> str | None:
    if isinstance(call.func, ast.Name):
        return call.func.id
    if isinstance(call.func, ast.Attribute):
        return call.func.attr
    return None


def _args_row_calls(node: ast.AST) -> list[ast.Call]:
    return [
        child
        for child in ast.walk(node)
        if isinstance(child, ast.Call) and isinstance(child.func, ast.Name) and child.func.id == "_args_row"
    ]


def _annotations(tree: ast.Module) -> Iterator[ast.expr]:
    for node in ast.walk(tree):
        if isinstance(node, (ast.arg, ast.AnnAssign)) and node.annotation is not None:
            yield node.annotation
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.returns is not None:
            yield node.returns


def _remove_client_modules() -> None:
    for name in list(sys.modules):
        if name == "specimen_client" or name.startswith("specimen_client."):
            del sys.modules[name]


@contextmanager
def _client_modules(
    full_package: Path,
) -> Iterator[tuple[ModuleType, ModuleType, Callable[[str], ModuleType]]]:
    original_path = sys.path.copy()
    previous = {
        name: module
        for name, module in sys.modules.items()
        if name == "specimen_client" or name.startswith("specimen_client.")
    }
    sys.path.insert(0, str(full_package / "src"))
    _remove_client_modules()
    try:
        root = importlib.import_module("specimen_client")
        sync = importlib.import_module("specimen_client.sync")
        yield root, sync, importlib.import_module
    finally:
        _remove_client_modules()
        sys.modules.update(previous)
        sys.path[:] = original_path


def _apply_migrations(db_url: str) -> None:
    migrations = sorted((FIXTURE_PROJECT / "migrations").glob("*.sql"), key=lambda path: int(path.stem))
    assert migrations, "fixture migrations are required for the registration canary"
    with psycopg.connect(db_url, autocommit=True) as conn:
        for migration in migrations:
            _ = conn.execute(migration.read_text().encode())


