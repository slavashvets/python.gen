def test_statement_ast_contract(generated_tree: Path) -> None:
    paths = _statement_paths(generated_tree)
    assert set(paths) == STATEMENTS

    for stem in sorted(STATEMENTS):
        tree = _parse(paths[stem])
        sql = _sql_assignments(tree)
        assert len(sql) == 1
        assert isinstance(sql[0], ast.Constant) and isinstance(sql[0].value, str)

        async_function = _top_function(tree, stem)
        sync_function = _top_function(tree, f"{stem}_sync")
        assert isinstance(async_function, ast.AsyncFunctionDef)
        assert isinstance(sync_function, ast.FunctionDef)

        expected_row = ROWS.get(stem)
        row_classes = [node for node in tree.body if isinstance(node, ast.ClassDef) and node.name.endswith("Row")]
        assert [node.name for node in row_classes] == ([] if expected_row is None else [expected_row])

        imports = [
            alias
            for node in tree.body
            if isinstance(node, ast.ImportFrom) and node.module == "psycopg.rows" and node.level == 0
            for alias in node.names
            if alias.name == "args_row" and alias.asname == "_args_row"
        ]
        expected_count = int(expected_row is not None)
        assert len(imports) == expected_count
        if expected_row is None:
            assert not _args_row_calls(tree)
            continue

        row_class = row_classes[0]
        assert len(row_class.decorator_list) == 1
        decorator = row_class.decorator_list[0]
        assert isinstance(decorator, ast.Call) and isinstance(decorator.func, ast.Name)
        assert decorator.func.id == "dataclass" and not decorator.args
        assert {keyword.arg: ast.literal_eval(keyword.value) for keyword in decorator.keywords} == {
            "frozen": True,
            "slots": True,
        }

        for function in (async_function, sync_function):
            calls = _args_row_calls(function)
            assert len(calls) == 1
            assert len(calls[0].args) == 1 and not calls[0].keywords
            assert isinstance(calls[0].args[0], ast.Name) and calls[0].args[0].id == expected_row
            returns = [node for node in function.body if isinstance(node, ast.Return)]
            assert len(returns) == 1 and returns[0].value is not None
            returned = returns[0].value.value if isinstance(returns[0].value, ast.Await) else returns[0].value
            assert isinstance(returned, ast.Call) and calls[0] in returned.args


def test_adapter_strategy_ast_contract(generated_tree: Path) -> None:
    forbidden_functions = {"_decode_row", "pg_decode", "pg_encode", "_cast", "model_dump", "model_validate"}
    forbidden_calls = forbidden_functions | {"cast", "parse_obj"}

    for path in _python_paths(generated_tree):
        tree = _parse(path)
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                assert node.name not in forbidden_functions and not node.name.startswith("decode_")
            elif isinstance(node, ast.Call):
                leaf = _call_leaf(node)
                assert leaf not in forbidden_calls and not (leaf or "").startswith("decode_")
            elif isinstance(node, ast.ImportFrom) and node.module == "typing":
                assert all(alias.name != "cast" for alias in node.names)

    for stem, path in _statement_paths(generated_tree).items():
        tree = _parse(path)
        row_imports = [
            (alias.name, alias.asname)
            for node in tree.body
            if isinstance(node, ast.ImportFrom) and node.module == "psycopg.rows" and node.level == 0
            for alias in node.names
        ]
        assert row_imports == ([] if stem == "bump_specimen_revision" else [("args_row", "_args_row")])

        custom_references = [
            node
            for annotation in _annotations(tree)
            for node in ast.walk(annotation)
            if isinstance(node, ast.Attribute)
            and isinstance(node.value, ast.Name)
            and node.value.id == "_db_types"
            and node.attr in CUSTOM_MODULES
        ]
        bare_custom = [
            node
            for annotation in _annotations(tree)
            for node in ast.walk(annotation)
            if isinstance(node, ast.Name) and node.id in CUSTOM_MODULES
        ]
        assert not bare_custom

        namespace_imports = [
            alias
            for node in tree.body
            if isinstance(node, ast.ImportFrom) and node.level == 2 and node.module is None
            for alias in node.names
            if alias.name == "types" and alias.asname == "_db_types"
        ]
        assert len(namespace_imports) == int(bool(custom_references))
        direct_leaf_imports = [
            node
            for node in tree.body
            if isinstance(node, ast.ImportFrom)
            and node.level > 0
            and (node.module == "types" or (node.module or "").startswith("types."))
        ]
        assert not direct_leaf_imports


def test_public_facade_identities_and_signatures(full_package: Path) -> None:
    with _client_modules(full_package) as (root, sync, import_module):
        assert root.sync is sync
        for stem in sorted(STATEMENTS):
            statement = import_module(f"specimen_client._generated.statements.{stem}")
            async_function = getattr(root, stem)
            sync_function = getattr(sync, stem)
            assert async_function is getattr(statement, stem)
            assert sync_function is getattr(statement, f"{stem}_sync")
            assert inspect.iscoroutinefunction(async_function)
            assert not inspect.iscoroutinefunction(sync_function)

            async_signature = inspect.signature(async_function)
            sync_signature = inspect.signature(sync_function)
            assert async_signature.return_annotation == sync_signature.return_annotation
            async_parameters = list(async_signature.parameters.values())
            sync_parameters = list(sync_signature.parameters.values())
            assert len(async_parameters) == len(sync_parameters)
            for index, (async_parameter, sync_parameter) in enumerate(
                zip(async_parameters, sync_parameters, strict=True)
            ):
                assert async_parameter.name == sync_parameter.name
                assert async_parameter.kind == sync_parameter.kind
                assert async_parameter.default == sync_parameter.default
                if index == 0:
                    assert async_parameter.annotation == "AsyncConnection[object]"
                    assert sync_parameter.annotation == "Connection[object]"
                else:
                    assert async_parameter.annotation == sync_parameter.annotation

            row_name = ROWS.get(stem)
            if row_name is not None:
                canonical_row = getattr(statement, row_name)
                assert getattr(root, row_name) is canonical_row
                assert getattr(sync, row_name) is canonical_row

        core = import_module("specimen_client._generated._core")
        for name in CORE_TYPES:
            assert getattr(root, name) is getattr(sync, name) is getattr(core, name)
        for name, leaf in CUSTOM_MODULES.items():
            module = import_module(f"specimen_client._generated.types.{leaf}")
            assert getattr(root, name) is getattr(sync, name) is getattr(module, name)


def test_generated_import_allowlist(generated_tree: Path) -> None:
    allowed_roots = sys.stdlib_module_names | {"__future__", "psycopg", "specimen_client"}
    violations: list[str] = []

    for path in _python_paths(generated_tree):
        tree = _parse(path)
        importlib_aliases: set[str] = set()
        import_module_aliases: set[str] = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    root = alias.name.partition(".")[0]
                    if root not in allowed_roots:
                        violations.append(f"{path}: absolute import {alias.name}")
                    if alias.name == "importlib":
                        importlib_aliases.add(alias.asname or alias.name)
            elif isinstance(node, ast.ImportFrom) and node.level == 0:
                root = (node.module or "").partition(".")[0]
                if root not in allowed_roots:
                    violations.append(f"{path}: absolute import from {node.module}")
                if node.module == "importlib":
                    import_module_aliases.update(
                        alias.asname or alias.name for alias in node.names if alias.name == "import_module"
                    )

        for node in ast.walk(tree):
            if not isinstance(node, ast.Call):
                continue
            if isinstance(node.func, ast.Name) and node.func.id == "__import__":
                violations.append(f"{path}:{node.lineno}: dynamic __import__")
            if isinstance(node.func, ast.Name) and node.func.id in import_module_aliases:
                violations.append(f"{path}:{node.lineno}: dynamic import_module")
            if (
                isinstance(node.func, ast.Attribute)
                and node.func.attr == "import_module"
                and isinstance(node.func.value, ast.Name)
                and node.func.value.id in importlib_aliases
            ):
                violations.append(f"{path}:{node.lineno}: dynamic importlib.import_module")

    assert not violations, "generated import boundary violations:\n" + "\n".join(violations)


def test_registration_static_and_api_contract(generated_tree: Path, full_package: Path) -> None:
    package = _generated_package(generated_tree)
    register_path = package / "_generated" / "_register.py"
    assert list(package.rglob("_register.py")) == [register_path]
    assert not (package / "_generated" / "sync" / "_register.py").exists()

    tree = _parse(register_path)
    metadata: dict[str, str] = {}
    callback_types: list[str] = []
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1:
            target = node.targets[0]
            if isinstance(target, ast.Name) and target.id.endswith("_pg_name"):
                assert isinstance(node.value, ast.Constant) and isinstance(node.value.value, str)
                metadata[target.id] = node.value.value
            if (
                isinstance(node.value, ast.Call)
                and isinstance(node.value.func, ast.Name)
                and node.value.func.id == "_dataclass_callbacks"
            ):
                argument = node.value.args[0]
                assert isinstance(argument, ast.Attribute) and isinstance(argument.value, ast.Name)
                assert argument.value.id == "_db_types"
                callback_types.append(argument.attr)

    assert metadata == {
        "_mood_pg_name": "public.mood",
        "_point_2_d_pg_name": "public.point2d",
        "_tag_value_pg_name": "public.tag_value",
        "_z_codec_payload_pg_name": "public.z_codec_payload",
        "_a_codec_wrapper_pg_name": "public.a_codec_wrapper",
    }
    assert callback_types == ["Point2D", "TagValue", "ZCodecPayload", "ACodecWrapper"]

    async_register = _top_function(tree, "register_types")
    sync_register = _top_function(tree, "register_types_sync")
    assert isinstance(async_register, ast.AsyncFunctionDef)
    assert isinstance(sync_register, ast.FunctionDef)
    expected_fetch_order = [
        "_mood_pg_name",
        "_point_2_d_pg_name",
        "_tag_value_pg_name",
        "_z_codec_payload_pg_name",
        "_a_codec_wrapper_pg_name",
    ]
    for function in (async_register, sync_register):
        fetch_calls = sorted(
            (
                node
                for node in ast.walk(function)
                if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr == "fetch"
            ),
            key=lambda node: node.lineno,
        )
        fetch_metadata = [
            call.args[1].id for call in fetch_calls if len(call.args) == 2 and isinstance(call.args[1], ast.Name)
        ]
        assert fetch_metadata == expected_fetch_order

    with _client_modules(full_package) as (root, sync, import_module):
        register = import_module("specimen_client._generated._register")
        assert root.register_types is register.register_types
        assert sync.register_types is register.register_types_sync
        assert "register_types" in root.__all__
        assert "register_types" in sync.__all__
        assert inspect.iscoroutinefunction(root.register_types)
        assert not inspect.iscoroutinefunction(sync.register_types)


def test_registration_roundtrip_two_surfaces(full_package: Path, roundtrip_db: str) -> None:
    _apply_migrations(roundtrip_db)
    with _client_modules(full_package) as (root, sync, _):

        async def write_and_read() -> tuple[int, int, int]:
            conn = await psycopg.AsyncConnection.connect(roundtrip_db, autocommit=True)
            try:
                await root.register_types(conn)
                tagged = await root.insert_tagged_item(
                    conn,
                    name="takeover-tag",
                    tag=root.TagValue(value="blue"),
                )
                tagged_hit = await root.get_tagged_item(conn, id=tagged.id)
                assert type(tagged) is root.InsertTaggedItemRow
                assert type(tagged_hit) is root.GetTaggedItemRow
                assert type(tagged_hit.tag) is root.TagValue

                payload = root.ZCodecPayload(class_=71, pg_decode="takeover", pg_encode=None)
                wrapper = root.ACodecWrapper(
                    payload=root.ZCodecPayload(class_=72, pg_decode="nested", pg_encode=None),
                    feeling=root.Mood.SAD,
                    note="canary",
                )
                specimen = await root.insert_specimen(
                    conn,
                    doc_jsonb={"contract": "takeover"},
                    feeling=root.Mood.HAPPY,
                    origin=root.Point2D(x=3.0, y=4.0),
                    flag=True,
                    small=1,
                    medium=2,
                    large=3,
                    ratio=0.5,
                    precise=0.25,
                    title="takeover-specimen",
                    code="T-1",
                    letter="t",
                    born_on=date(2026, 7, 13),
                    amount=Decimal("7.13"),
                    blob=b"takeover",
                    doc_json=["canary"],
                    maybe_text=None,
                    maybe_int=None,
                    maybe_uuid=None,
                    maybe_ts=None,
                    maybe_num=None,
                    tags=["contract"],
                    related_ids=None,
                    grid=None,
                    moods=[root.Mood.HAPPY, None],
                    codec_payload=payload,
                    codec_payloads=[payload],
                    codec_wrapper=wrapper,
                )
                specimen_hit = await root.get_specimen(conn, id=specimen.id)
                assert type(specimen) is root.InsertSpecimenRow
                assert type(specimen_hit) is root.GetSpecimenRow
                assert type(specimen_hit.codec_payload) is root.ZCodecPayload
                assert type(specimen_hit.codec_wrapper) is root.ACodecWrapper
                assert type(specimen_hit.codec_wrapper.payload) is root.ZCodecPayload
                return tagged.id, specimen.id, conn.info.backend_pid
            finally:
                await conn.close()

        tagged_id, specimen_id, async_backend_pid = asyncio.run(write_and_read())
        with psycopg.connect(roundtrip_db, autocommit=True) as conn:
            assert conn.info.backend_pid != async_backend_pid
            sync.register_types(conn)
            tagged_hit = sync.get_tagged_item(conn, id=tagged_id)
            specimen_hit = sync.get_specimen(conn, id=specimen_id)
            assert type(tagged_hit) is sync.GetTaggedItemRow is root.GetTaggedItemRow
            assert type(tagged_hit.tag) is sync.TagValue is root.TagValue
            assert type(specimen_hit) is sync.GetSpecimenRow is root.GetSpecimenRow
            assert type(specimen_hit.codec_wrapper) is sync.ACodecWrapper is root.ACodecWrapper
            assert type(specimen_hit.codec_wrapper.payload) is sync.ZCodecPayload is root.ZCodecPayload


